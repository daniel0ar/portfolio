#!/usr/bin/env node
// Prompts for the admin password and stores only its scrypt hash.
const fs = require('fs');
const path = require('path');
const readline = require('readline');
const { hashPassword } = require('../api/_lib/auth');

const TARGET = path.join(__dirname, '..', 'api', '_lib', 'password-hash.js');
const MIN_LENGTH = 16;

function ask(prompt) {
    return new Promise((resolve) => {
        const rl = readline.createInterface({ input: process.stdin, output: process.stdout, terminal: true });
        rl.question(prompt, (answer) => {
            rl.close();
            process.stdout.write('\n');
            resolve(answer);
        });
        rl._writeToOutput = (text) => {
            if (text.includes(prompt)) process.stdout.write(prompt);
        };
    });
}

(async () => {
    const password = await ask('New admin password: ');
    if (password.length < MIN_LENGTH) {
        console.error(`Use at least ${MIN_LENGTH} characters. The hash is stored in the repository.`);
        process.exit(1);
    }
    if (password !== await ask('Repeat password: ')) {
        console.error('The passwords do not match.');
        process.exit(1);
    }

    const hash = await hashPassword(password);
    fs.writeFileSync(
        TARGET,
        `// Generated by \`node scripts/hash-password.js\`. Login stays disabled while empty.\nmodule.exports = '${hash}';\n`,
    );
    console.log('Saved the hash to api/_lib/password-hash.js');
})();
